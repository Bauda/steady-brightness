#pragma once
#include "common.h"

namespace Startup {
inline constexpr wchar_t RunKey[] = L"Software\\Microsoft\\Windows\\CurrentVersion\\Run";
inline constexpr wchar_t ApprovalKey[] = L"Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\StartupApproved\\Run";
inline constexpr wchar_t Entry[] = L"SteadyBrightness";
inline constexpr wchar_t Argument[] = L"\" --background";
inline constexpr size_t MaxCommand = 260;

enum class State { Off, On, Broken, DisabledByWindows, Unknown };

inline LONG Write(const wchar_t* key, const std::wstring& exe, bool enable) {
    if (!enable) {
        LONG result = RegDeleteKeyValueW(HKEY_CURRENT_USER, key, Entry);
        return result == ERROR_FILE_NOT_FOUND || result == ERROR_PATH_NOT_FOUND ? ERROR_SUCCESS : result;
    }
    if (exe.empty()) return ERROR_INVALID_PARAMETER;
    std::wstring command = L"\"" + exe + Argument;
    if (command.size() > MaxCommand) return ERROR_FILENAME_EXCED_RANGE;
    return RegSetKeyValueW(HKEY_CURRENT_USER, key, Entry, REG_SZ, command.c_str(),
        static_cast<DWORD>((command.size() + 1) * sizeof(wchar_t)));
}

inline State Read(const wchar_t* key = RunKey, const wchar_t* approval = ApprovalKey) {
    wchar_t data[MaxCommand + 1]{};
    DWORD bytes = sizeof(data);
    LONG result = RegGetValueW(HKEY_CURRENT_USER, key, Entry, RRF_RT_REG_SZ, nullptr, data, &bytes);
    if (result == ERROR_FILE_NOT_FOUND || result == ERROR_PATH_NOT_FOUND) return State::Off;
    if (result == ERROR_MORE_DATA || result == ERROR_UNSUPPORTED_TYPE) return State::Broken;
    if (result != ERROR_SUCCESS) return State::Unknown;

    // Explorer can disable a Run entry without removing it. Recognize its
    // known disabled records on a best-effort basis, and never edit them.
    DWORD approvalData[3]{};
    bytes = sizeof(approvalData);
    if (RegGetValueW(HKEY_CURRENT_USER, approval, Entry, RRF_RT_REG_BINARY, nullptr,
        approvalData, &bytes) == ERROR_SUCCESS && bytes == sizeof(approvalData)
        && (approvalData[0] == 3 || approvalData[0] == 7)) return State::DisabledByWindows;

    // Match the exact quoted command generated by the app, including older releases.
    if (data[0] != L'"') return State::Broken;
    wchar_t* pathEnd = wcschr(data + 1, L'"');
    if (!pathEnd || _wcsicmp(pathEnd, Argument) != 0) return State::Broken;
    *pathEnd = L'\0';
    DWORD attributes = GetFileAttributesW(data + 1);
    if (attributes != INVALID_FILE_ATTRIBUTES && !(attributes & FILE_ATTRIBUTE_DIRECTORY)) return State::On;
    return State::Broken;
}
}
